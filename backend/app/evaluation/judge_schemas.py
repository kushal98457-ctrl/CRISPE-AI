"""Pydantic schemas and structured output contracts for Model-Assisted Evaluation (Step 21).

Defines the typed output contracts for the LLM judge, individual dimension ratings,
evaluation results, and combined deterministic + model-assisted reports.
"""

from datetime import datetime, timezone
import re
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator

from app.evaluation.check_schemas import EvaluationExampleResult
from app.evaluation.judge_rubric import ModelJudgeDimension
from app.schemas.crispe import ModelUsageMetadata


class DimensionEvaluation(BaseModel):
    """Evaluation verdict and evidence for a single rubric dimension."""

    model_config = ConfigDict(extra="forbid", use_enum_values=True)

    dimension: ModelJudgeDimension = Field(..., description="The rubric dimension being graded.")
    applicable: bool = Field(default=True, description="Whether this dimension applies to the task.")
    score: Optional[int] = Field(
        default=None,
        ge=0,
        le=4,
        description="Ordinal score from 0 (inadequate) to 4 (strong). Required if applicable is True.",
    )
    rationale: str = Field(
        ...,
        min_length=10,
        max_length=1500,
        description="Concrete, evidence-based justification for the assigned rating.",
    )
    evidence_quote: Optional[str] = Field(
        default=None,
        max_length=500,
        description="Short direct excerpt from the generated prompt illustrating the rating.",
    )
    missing_requirements: List[str] = Field(
        default_factory=list,
        description="Specific requirements or constraints omitted by the prompt in this dimension.",
    )
    insufficient_evidence: bool = Field(
        default=False,
        description="Flag indicating that available task evidence was insufficient for a confident rating.",
    )

    @model_validator(mode="after")
    def validate_score_for_applicability(self) -> "DimensionEvaluation":
        """Enforce that applicable dimensions must provide an integer score in 0..4."""
        if self.applicable and self.score is None:
            raise ValueError(f"Dimension '{self.dimension}' is applicable but provided no score.")
        return self


class ModelJudgeResponse(BaseModel):
    """Structured JSON output contract generated by the LLM-as-a-judge model."""

    model_config = ConfigDict(extra="forbid", use_enum_values=True)

    dimensions: List[DimensionEvaluation] = Field(
        ...,
        min_length=1,
        description="List of dimension-level ratings conforming to the rubric.",
    )
    critical_issues: List[str] = Field(
        default_factory=list,
        description="Serious omissions, contradictions, or violations that impair the prompt.",
    )
    summary_weaknesses: List[str] = Field(
        default_factory=list,
        description="Actionable diagnostic feedback identifying specific areas needing improvement.",
    )
    suggested_improvements: List[str] = Field(
        default_factory=list,
        description="Concrete, constructive suggestions for future prompt reflection / optimization.",
    )
    overall_verdict: str = Field(
        ...,
        description="High-level evaluation verdict: 'PASS', 'MARGINAL', or 'FAIL'.",
    )

    @field_validator("overall_verdict")
    @classmethod
    def validate_verdict(cls, v: str) -> str:
        cleaned = v.strip().upper()
        if cleaned not in ("PASS", "MARGINAL", "FAIL"):
            raise ValueError(f"overall_verdict must be 'PASS', 'MARGINAL', or 'FAIL', got '{v}'")
        return cleaned


class ModelEvaluationResult(BaseModel):
    """Complete evaluation outcome from the model-assisted judge service."""

    model_config = ConfigDict(extra="forbid", use_enum_values=True)

    evaluation_id: str = Field(..., description="Unique evaluation record identifier.")
    example_id: str = Field(..., description="Dataset benchmark example identifier.")
    dataset_version: str = Field(..., description="Evaluation dataset version.")
    rubric_version: str = Field(default="v1.0", description="Evaluation rubric version used.")
    judge_instruction_version: str = Field(default="v1.0", description="Judge instruction prompt version.")
    evaluator_model_id: str = Field(..., description="Exact model checkpoint identifier used as judge.")
    status: str = Field(
        ...,
        description="Execution status: 'SUCCESS', 'EVALUATOR_FAILED', or 'SKIPPED'.",
    )
    dimensions: Dict[str, DimensionEvaluation] = Field(
        ...,
        description="Map of dimension identifier to detailed dimension evaluation.",
    )
    mean_dimension_score: float = Field(
        ...,
        ge=0.0,
        le=4.0,
        description="Average score across applicable dimensions on the 0-4 scale.",
    )
    normalized_model_score: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Normalized score on a 0.0 to 1.0 scale (mean_dimension_score / 4.0).",
    )
    critical_issues: List[str] = Field(default_factory=list, description="Critical deficiencies identified.")
    summary_weaknesses: List[str] = Field(default_factory=list, description="Diagnostic summary of weaknesses.")
    suggested_improvements: List[str] = Field(default_factory=list, description="Targeted recommendations.")
    usage: Optional[ModelUsageMetadata] = Field(default=None, description="Judge token consumption metadata.")
    latency_ms: Optional[float] = Field(default=None, ge=0.0, description="Judge roundtrip latency in ms.")
    error_message: Optional[str] = Field(default=None, description="Diagnostic error details if failed.")
    evaluated_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="UTC completion timestamp.",
    )


class CombinedEvaluationResult(BaseModel):
    """Unified evaluation record integrating deterministic and model-assisted results."""

    model_config = ConfigDict(extra="forbid", use_enum_values=True)

    evaluation_id: str = Field(..., description="Unique combined evaluation identifier.")
    example_id: str = Field(..., description="Dataset benchmark example identifier.")
    dataset_version: str = Field(..., description="Evaluation dataset version.")
    combined_status: str = Field(
        ...,
        description="'SUCCESS', 'PARTIAL_SUCCESS' (deterministic only), or 'FAILED'.",
    )
    deterministic_result: EvaluationExampleResult = Field(
        ...,
        description="Full deterministic check results and scoring from Step 20.",
    )
    model_result: Optional[ModelEvaluationResult] = Field(
        default=None,
        description="Model-assisted evaluation results if enabled and executed.",
    )
    deterministic_score: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Normalized deterministic score [0.0, 1.0].",
    )
    model_assisted_score: Optional[float] = Field(
        default=None,
        ge=0.0,
        le=1.0,
        description="Normalized model-assisted score [0.0, 1.0] if executed.",
    )
    composite_score: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Combined overall prompt quality score [0.0, 1.0] after penalty capping.",
    )
    critical_failure: bool = Field(
        ...,
        description="Whether a deterministic or model-based critical failure occurred.",
    )
    critical_failure_reasons: List[str] = Field(
        default_factory=list,
        description="Explanations for triggered critical penalties.",
    )
    disagreements: List[str] = Field(
        default_factory=list,
        description="Identified discrepancies between deterministic checks and judge ratings.",
    )
    evaluated_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="UTC timestamp of combined evaluation.",
    )
